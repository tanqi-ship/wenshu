-- G-005 黄金 SQL：单指标 + 闭区间时间（2026-01-31 ~ 2026-06-30）
--
-- ★ 这条是**手写**的，不是引擎产出的。
--
-- 形状：range_between
--   SELECT <指标表达式> AS <指标 code>
--   FROM <来源表> AS t1
--   WHERE t1.etl_dt BETWEEN '<起>' AND '<止>'
--
-- 钉住三件事：
--
--   ① **边界的值就是 Intent 给的日期，编译器不推算。**
--      "2026年1月到6月"落到 etl_dt 上，起止必须是月末快照 2026-01-31 与
--      2026-06-30，而不是 2026-01-01。这个推算是 L1/L2 的活；
--      编译器只负责把给它的两个日期原样变成闭区间。
--
--   ② **必须是闭区间 BETWEEN，不是 >= 加 < 。**
--      半开区间会把 6 月末那个快照漏掉，少一个月，而数字只差一点、
--      完全看不出来。
--
--   ③ 用 t1. 前缀，且 loan_balance 的公式在语义层里**不带** {tbl} 占位符
--      （SUM(current_balnc_cny)），靠 qualify_columns 补别名 ——
--      所以这条同时钉住"补别名"对时间不敏感。
--
-- ⚠️ 口径提醒（这条钉形状，不钉口径）：
--      余额是**时点存量**，对 6 个月末快照求和没有业务意义（会把余额累加）。
--      区间形态适用的是流量类指标（核销金额、回收金额）。
--      "区间里的月份该不该逐月累加"是 L2 门禁/语义层该判断的事，
--      编译器不做业务判断 —— 这条用例的存在是为了钉形状，不是认可这个口径。
--
-- 对应语义层：bank_mini.py 的 loan_balance
-- 对应 fixture：qa_loan_acc_detail（注意 D-10：库里**没有** 2026-03-31 的快照）
-- 对应评测：AQ-009（2026年3月末余额，正是 D-10 的正面用例）
-- 对应规则：D-10（时点缺失）

SELECT
  SUM(t1.current_balnc_cny) AS loan_balance
FROM qa_loan_acc_detail AS t1
WHERE
  t1.etl_dt BETWEEN '2026-01-31' AND '2026-06-30'
